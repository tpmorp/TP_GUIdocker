//----------------------------------------------------------------------------------
//	切り替え中の窓を描かせない
//	有効化・無効化・終了・ワークスペースの作り直しの間、本体が切り離した窓を Windows に描かせず
//	(DWMWA_CLOAK)、大量の窓が一瞬並ぶのを見せない。本体の窓は出したまま、覆いで中を隠す
//----------------------------------------------------------------------------------
#pragma once
#include "common.h"

namespace tpgd {

// 開始: 今出ている切り離し窓と、これから現れる切り離し窓を描かせない
void cloak_begin(HWND main);

// 1枚だけ描かせる状態へ戻す (取り込みの直前に使う。子窓になると属性を外せなくなるため)
void cloak_release(HWND h);

// 描かせない最中なら、今出ている切り離し窓も描かせない (返却で独立窓に戻った直後に使う)
void cloak_refresh();

// 終了: すべて描かせる状態へ戻す
void cloak_end();

} // namespace tpgd
